package com.biokey.security

import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import android.util.Base64
import androidx.annotation.RequiresApi
import androidx.biometric.BiometricManager
import androidx.biometric.BiometricManager.Authenticators
import androidx.biometric.BiometricPrompt
import androidx.core.content.ContextCompat
import androidx.fragment.app.FragmentActivity
import java.security.KeyStore
import java.security.SecureRandom
import java.security.cert.Certificate
import java.security.cert.X509Certificate
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import kotlin.coroutines.resume
import kotlinx.coroutines.suspendCancellableCoroutine

/**
 * Hardened Biometric and Hardware Security Manager for BioKey.
 *
 * Implements Class 3 (Strong) Biometric Enforcement, StrongBox KeyMint hardware isolation,
 * Per-Operation Cryptographic Binding (Auth-Bound Keys), and zero-fallback policy.
 */
class BiometricAuthManager(
    private val context: Context,
    private val keyAlias: String = DEFAULT_KEY_ALIAS,
    private val requireStrongBox: Boolean = true
) {

    companion object {
        const val DEFAULT_KEY_ALIAS = "BioKey_Master_AuthBound_Key"
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val AES_GCM_NOPADDING = "AES/GCM/NoPadding"
        private const val GCM_IV_LENGTH_BYTES = 12
        private const val GCM_TAG_LENGTH_BITS = 128

        // ASN.1 OID for Android KeyStore Attestation Extension
        const val KEY_ATTESTATION_OID = "1.3.6.1.4.1.11129.2.1.17"
    }

    private val keyStore: KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply {
        load(null)
    }

    private val biometricManager = BiometricManager.from(context)

    // =========================================================================
    // 1. Biometric Capability & Readiness Verification
    // =========================================================================

    sealed class BiometricReadiness {
        object Ready : BiometricReadiness()
        object NoHardware : BiometricReadiness()
        object HardwareUnavailable : BiometricReadiness()
        object NoneEnrolled : BiometricReadiness()
        object SecurityUpdateRequired : BiometricReadiness()
        data class Unsupported(val rawStatusCode: Int) : BiometricReadiness()
    }

    /**
     * Checks if Class 3 (BIOMETRIC_STRONG) hardware is present, operational, and enrolled.
     * Insecure fallback (DEVICE_CREDENTIAL) is deliberately excluded from evaluation.
     */
    fun checkBiometricReadiness(): BiometricReadiness {
        return when (biometricManager.canAuthenticate(Authenticators.BIOMETRIC_STRONG)) {
            BiometricManager.BIOMETRIC_SUCCESS -> BiometricReadiness.Ready
            BiometricManager.BIOMETRIC_ERROR_NO_HARDWARE -> BiometricReadiness.NoHardware
            BiometricManager.BIOMETRIC_ERROR_HW_UNAVAILABLE -> BiometricReadiness.HardwareUnavailable
            BiometricManager.BIOMETRIC_ERROR_NONE_ENROLLED -> BiometricReadiness.NoneEnrolled
            BiometricManager.BIOMETRIC_ERROR_SECURITY_UPDATE_REQUIRED -> BiometricReadiness.SecurityUpdateRequired
            else -> BiometricReadiness.Unsupported(
                biometricManager.canAuthenticate(Authenticators.BIOMETRIC_STRONG)
            )
        }
    }

    // =========================================================================
    // 2. Hardware-Backed StrongBox Key Generation & Cryptographic Binding
    // =========================================================================

    /**
     * Generates or retrieves an auth-bound AES-256-GCM key inside StrongBox / TEE KeyMint.
     *
     * Architectural Guarantees:
     * 1. StrongBox-backed: Key material resides in dedicated tamper-resistant hardware (eSE / Titan M2).
     * 2. setUserAuthenticationRequired(true) + timeout=0: Requires a fresh HardwareAuthToken (HAT)
     *    generated by a Class 3 biometric authenticator for every single cryptographic operation.
     * 3. AUTH_BIOMETRIC_STRONG: KeyMint will reject any HAT signed by GateKeeper (PIN/Password).
     * 4. setInvalidatedByBiometricEnrollment(true): Key is permanently destroyed/invalidated if
     *    a new fingerprint or face is enrolled in Android Settings, mitigating rogue enrollment attacks.
     *
     * @param attestationChallenge Optional server-provided challenge to request an X.509
     *                             hardware attestation certificate chain.
     */
    @Synchronized
    fun getOrCreateAuthBoundKey(attestationChallenge: ByteArray? = null): SecretKey {
        if (keyStore.containsAlias(keyAlias)) {
            val key = keyStore.getKey(keyAlias, null) as? SecretKey
            if (key != null) return key
            keyStore.deleteEntry(keyAlias)
        }

        val hasStrongBox = context.packageManager.hasSystemFeature(PackageManager.FEATURE_STRONGBOX_KEYSTORE)
        val useStrongBox = requireStrongBox && hasStrongBox

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )

        val specBuilder = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setUserAuthenticationRequired(true)

        // API 30+ enforces explicit authenticator types. We mandate BIOMETRIC_STRONG ONLY.
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            specBuilder.setUserAuthenticationParameters(
                0, // 0 = Per-operation authorization (auth-per-use)
                KeyProperties.AUTH_BIOMETRIC_STRONG // Strict: NO KeyProperties.AUTH_DEVICE_CREDENTIAL
            )
        } else {
            @Suppress("DEPRECATION")
            specBuilder.setUserAuthenticationValidityDurationSeconds(-1) // -1 = per-use in legacy API
        }

        // Invalidate permanently if attacker adds a new biometric fingerprint/face in Settings
        specBuilder.setInvalidatedByBiometricEnrollment(true)

        // Remote Hardware Attestation Challenge (KeyMint root of trust verification)
        if (attestationChallenge != null && attestationChallenge.isNotEmpty()) {
            specBuilder.setAttestationChallenge(attestationChallenge)
        }

        // Configure StrongBox isolation
        if (useStrongBox) {
            specBuilder.setIsStrongBoxBacked(true)
        }

        return try {
            keyGenerator.init(specBuilder.build())
            keyGenerator.generateKey()
        } catch (e: Exception) {
            if (useStrongBox && (e is StrongBoxUnavailableException || e.javaClass.name.contains("StrongBox"))) {
                // Graceful fallback to TEE KeyMint if device reports StrongBox feature but chip is busy/failed
                specBuilder.setIsStrongBoxBacked(false)
                keyGenerator.init(specBuilder.build())
                keyGenerator.generateKey()
            } else {
                throw e
            }
        }
    }

    /**
     * Retrieves the X.509 hardware key attestation certificate chain for remote verification.
     */
    fun getKeyAttestationChain(): List<Certificate>? {
        return keyStore.getCertificateChain(keyAlias)?.toList()
    }

    /**
     * Explicitly deletes the master key and purges cryptographic state.
     */
    fun deleteMasterKey() {
        if (keyStore.containsAlias(keyAlias)) {
            keyStore.deleteEntry(keyAlias)
        }
    }

    // =========================================================================
    // 3. Cryptographic Operations: Auth-Bound Encrypt & Decrypt
    // =========================================================================

    data class EncryptedPayload(
        val iv: ByteArray,
        val ciphertext: ByteArray
    ) {
        fun encodeToString(): String {
            val ivStr = Base64.encodeToString(iv, Base64.NO_WRAP)
            val cipherStr = Base64.encodeToString(ciphertext, Base64.NO_WRAP)
            return "$ivStr:$cipherStr"
        }

        companion object {
            fun decodeFromString(encoded: String): EncryptedPayload {
                val parts = encoded.split(":")
                require(parts.size == 2) { "Invalid encrypted payload format" }
                val iv = Base64.decode(parts[0], Base64.NO_WRAP)
                val ciphertext = Base64.decode(parts[1], Base64.NO_WRAP)
                return EncryptedPayload(iv, ciphertext)
            }
        }

        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (javaClass != other?.javaClass) return false
            other as EncryptedPayload
            return iv.contentEquals(other.iv) && ciphertext.contentEquals(other.ciphertext)
        }

        override fun hashCode(): Int = 31 * iv.contentHashCode() + ciphertext.contentHashCode()
    }

    /**
     * Initializes an auth-bound AES-GCM Cipher for ENCRYPTION.
     * The returned Cipher has received an operation handle from KeyMint, but CANNOT encrypt
     * until BiometricPrompt satisfies the HardwareAuthToken challenge.
     */
    fun initEncryptionCipher(): Cipher {
        val key = getOrCreateAuthBoundKey()
        val cipher = Cipher.getInstance(AES_GCM_NOPADDING)
        // Cipher.init() triggers KeyMint.begin(), registering the operation handle
        cipher.init(Cipher.ENCRYPT_MODE, key)
        return cipher
    }

    /**
     * Initializes an auth-bound AES-GCM Cipher for DECRYPTION using the stored IV.
     */
    fun initDecryptionCipher(iv: ByteArray): Cipher {
        val key = getOrCreateAuthBoundKey()
        val cipher = Cipher.getInstance(AES_GCM_NOPADDING)
        val spec = GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv)
        cipher.init(Cipher.DECRYPT_MODE, key, spec)
        return cipher
    }

    // =========================================================================
    // 4. Biometric Prompt Execution & Callback Handling
    // =========================================================================

    sealed class AuthResult {
        data class EncryptionSuccess(val encryptedPayload: EncryptedPayload) : AuthResult()
        data class DecryptionSuccess(val plaintext: ByteArray) : AuthResult()
        data class Error(val errorCode: Int, val errString: CharSequence) : AuthResult()
        object Failed : AuthResult()
        object UserCanceled : AuthResult()
        object KeyPermanentlyInvalidated : AuthResult()
    }

    /**
     * Performs mandatory Class 3 Biometric Authentication to ENCRYPT sensitive plaintext.
     *
     * Insecure PIN/Pattern/Password fallback is strictly disabled:
     * - Allowed authenticators is set exclusively to BIOMETRIC_STRONG.
     * - DEVICE_CREDENTIAL is not permitted.
     * - Negative button is set to "Cancel".
     */
    suspend fun authenticateAndEncrypt(
        activity: FragmentActivity,
        plaintext: ByteArray,
        title: String = "BioKey Secure Authentication",
        subtitle: String = "Biometric identity verification required",
        description: String = "Class 3 hardware biometric authentication required to access encryption keys."
    ): AuthResult = suspendCancellableCoroutine { continuation ->
        val cipher = try {
            initEncryptionCipher()
        } catch (e: KeyPermanentlyInvalidatedException) {
            continuation.resume(AuthResult.KeyPermanentlyInvalidated)
            return@suspendCancellableCoroutine
        } catch (e: Exception) {
            continuation.resume(AuthResult.Error(-1, e.message ?: "Cipher initialization failed"))
            return@suspendCancellableCoroutine
        }

        val promptInfo = BiometricPrompt.PromptInfo.Builder()
            .setTitle(title)
            .setSubtitle(subtitle)
            .setDescription(description)
            // MANDATORY BIOMETRIC ENFORCEMENT:
            // Explicitly set BIOMETRIC_STRONG only. DEVICE_CREDENTIAL is completely absent.
            .setAllowedAuthenticators(Authenticators.BIOMETRIC_STRONG)
            // Mutual exclusivity: Android forbids setNegativeButtonText if DEVICE_CREDENTIAL is set.
            // Setting setNegativeButtonText ensures the OS UI never displays "Use PIN/Password".
            .setNegativeButtonText("Cancel")
            .build()

        val executor = ContextCompat.getMainExecutor(activity)
        val prompt = BiometricPrompt(activity, executor, object : BiometricPrompt.AuthenticationCallback() {
            override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) {
                super.onAuthenticationSucceeded(result)
                val authenticatedCipher = result.cryptoObject?.cipher
                if (authenticatedCipher == null) {
                    continuation.resume(AuthResult.Error(-2, "Null CryptoObject cipher returned"))
                    return
                }

                try {
                    // This call passes the HardwareAuthToken (HAT) into KeyMint.
                    // If the callback was hooked or forged in userland, doFinal will throw
                    // UserNotAuthenticatedException / KeyStoreException because KeyMint has no valid HAT.
                    val ciphertext = authenticatedCipher.doFinal(plaintext)
                    val iv = authenticatedCipher.iv
                    continuation.resume(AuthResult.EncryptionSuccess(EncryptedPayload(iv, ciphertext)))
                } catch (e: Exception) {
                    continuation.resume(AuthResult.Error(-3, "KeyMint operation failed: ${e.message}"))
                }
            }

            override fun onAuthenticationFailed() {
                super.onAuthenticationFailed()
                // Soft failure (unrecognized finger/face) - Android prompt remains open for retries
            }

            override fun onAuthenticationError(errorCode: Int, errString: CharSequence) {
                super.onAuthenticationError(errorCode, errString)
                when (errorCode) {
                    BiometricPrompt.ERROR_USER_CANCELED,
                    BiometricPrompt.ERROR_NEGATIVE_BUTTON -> continuation.resume(AuthResult.UserCanceled)
                    else -> continuation.resume(AuthResult.Error(errorCode, errString))
                }
            }
        })

        continuation.invokeOnCancellation {
            prompt.cancelAuthentication()
        }

        // Cryptographic Object wrapping ensures hardware-enforced token exchange
        prompt.authenticate(promptInfo, BiometricPrompt.CryptoObject(cipher))
    }

    /**
     * Performs mandatory Class 3 Biometric Authentication to DECRYPT an EncryptedPayload.
     */
    suspend fun authenticateAndDecrypt(
        activity: FragmentActivity,
        payload: EncryptedPayload,
        title: String = "BioKey Secure Unlock",
        subtitle: String = "Biometric identity verification required",
        description: String = "Class 3 hardware biometric authentication required to decrypt master credentials."
    ): AuthResult = suspendCancellableCoroutine { continuation ->
        val cipher = try {
            initDecryptionCipher(payload.iv)
        } catch (e: KeyPermanentlyInvalidatedException) {
            continuation.resume(AuthResult.KeyPermanentlyInvalidated)
            return@suspendCancellableCoroutine
        } catch (e: Exception) {
            continuation.resume(AuthResult.Error(-1, e.message ?: "Cipher decryption init failed"))
            return@suspendCancellableCoroutine
        }

        val promptInfo = BiometricPrompt.PromptInfo.Builder()
            .setTitle(title)
            .setSubtitle(subtitle)
            .setDescription(description)
            .setAllowedAuthenticators(Authenticators.BIOMETRIC_STRONG)
            .setNegativeButtonText("Cancel")
            .build()

        val executor = ContextCompat.getMainExecutor(activity)
        val prompt = BiometricPrompt(activity, executor, object : BiometricPrompt.AuthenticationCallback() {
            override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) {
                super.onAuthenticationSucceeded(result)
                val authenticatedCipher = result.cryptoObject?.cipher
                if (authenticatedCipher == null) {
                    continuation.resume(AuthResult.Error(-2, "Null CryptoObject cipher returned"))
                    return
                }

                try {
                    // KeyMint validates HardwareAuthToken and decrypts plaintext in secure hardware
                    val plaintext = authenticatedCipher.doFinal(payload.ciphertext)
                    continuation.resume(AuthResult.DecryptionSuccess(plaintext))
                } catch (e: Exception) {
                    continuation.resume(AuthResult.Error(-3, "KeyMint decryption failed: ${e.message}"))
                }
            }

            override fun onAuthenticationFailed() {
                super.onAuthenticationFailed()
            }

            override fun onAuthenticationError(errorCode: Int, errString: CharSequence) {
                super.onAuthenticationError(errorCode, errString)
                when (errorCode) {
                    BiometricPrompt.ERROR_USER_CANCELED,
                    BiometricPrompt.ERROR_NEGATIVE_BUTTON -> continuation.resume(AuthResult.UserCanceled)
                    else -> continuation.resume(AuthResult.Error(errorCode, errString))
                }
            }
        })

        continuation.invokeOnCancellation {
            prompt.cancelAuthentication()
        }

        prompt.authenticate(promptInfo, BiometricPrompt.CryptoObject(cipher))
    }
}
